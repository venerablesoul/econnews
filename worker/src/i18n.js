export const LANGS = ["en", "ru"];
export const DEFAULT_LANG = "en";

export function norm(lang) {
  const l = String(lang || "").trim().toLowerCase().slice(0, 2);
  return LANGS.includes(l) ? l : DEFAULT_LANG;
}

